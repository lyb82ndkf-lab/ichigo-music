const JAPANESE_CHAR_REGEX = /[\u3040-\u30ff\u31f0-\u31ff]/;

/**
 * Checks whether text contains Japanese characters (Hiragana / Katakana)
 */
export function isJapaneseText(text) {
  if (!text || typeof text !== 'string') return false;
  return JAPANESE_CHAR_REGEX.test(text);
}

/**
 * Parses a Japanese text line into segments with ruby annotations.
 * Supports longest-match compound parsing up to 4 characters.
 * @param {string} text 
 * @returns {Array<{ text: string, ruby?: string }>}
 */
export function annotateFurigana(text) {
  if (!text || typeof text !== 'string') return [];
  const result = [];
  let i = 0;
  const len = text.length;

  while (i < len) {
    // 1. Try compound word match (priority longest-match from length 4 down to 2)
    let matched = false;
    for (let cLen = 4; cLen >= 2; cLen--) {
      if (i + cLen <= len) {
        const sub = text.slice(i, i + cLen);
        if (JPOP_COMPOUNDS[sub]) {
          result.push({ text: sub, ruby: JPOP_COMPOUNDS[sub] });
          i += cLen;
          matched = true;
          break;
        }
      }
    }
    if (matched) continue;

    const char = text[i];

    // 2. Check if char is Kanji
    if (KANJI_REGEX.test(char)) {
      const ruby = SINGLE_KANJI_DICT[char];
      if (ruby) {
        result.push({ text: char, ruby });
      } else {
        result.push({ text: char });
      }
      i++;
    } else {
      // 3. Hiragana, Katakana, Romaji, punctuation
      let nonKanji = char;
      i++;
      while (i < len && !KANJI_REGEX.test(text[i])) {
        nonKanji += text[i];
        i++;
      }
      result.push({ text: nonKanji });
    }
  }

  return result;
}

/**
 * Returns HTML ruby markup for Japanese text
 * e.g. <ruby>未来<rt>みらい</rt></ruby>への<ruby>航海<rt>こうかい</rt></ruby>
 */
export function toRubyHtml(text, enabled = true) {
  if (!text || typeof text !== 'string') return '';
  if (enabled === false) return text;
  const segments = annotateFurigana(text);
  const html = segments.map(s => {
    if (s.ruby) {
      return `<ruby>${s.text}<rt>${s.ruby}</rt></ruby>`;
    }
    return s.text;
  }).join('');
  return html;
}
